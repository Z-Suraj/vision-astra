export function buildSeedRegions(): GeographicRegion[] {
  return REGION_SPECS.map((spec) => {
    const { elevationGrid, temperatureGrid } = buildParametricReferenceGrid({
      seedStr: spec.id,
      minM: spec.minM,
      maxM: spec.maxM,
      meanM: spec.meanM,
      slopeMeanDeg: spec.slopeMeanDeg,
      roughnessTriM: spec.roughnessTriM,
      morphology: spec.morphology,
      tempMeanK: spec.tempMeanK,
      tempMinK: spec.tempMinK,
      tempMaxK: spec.tempMaxK,
      size: 32,
    });

    const computed = extractTerrainFeaturesFromGrid(spec.id, elevationGrid, spec.cellSizeMeters, {
      temperatureGrid,
      geomorphologyClass: spec.geomorphologyClass,
      geologyNotes: spec.geologyNotes,
      featureSourceType: 'SYNTHETIC_GEOMORPHIC_PROXY',
      targetGridSize: 32,
    });

    // Anchor summary statistics explicitly to the published reference values while keeping
    // the spatial grids aligned for 3D visualization & heatmap inspection.
    computed.elevationMinM = spec.minM;
    computed.elevationMaxM = spec.maxM;
    computed.elevationMeanM = spec.meanM;
    computed.elevationReliefM = Number((spec.maxM - spec.minM).toFixed(2));
    computed.slopeMeanDeg = spec.slopeMeanDeg;
    computed.roughnessTriM = spec.roughnessTriM;
    if (spec.tempMeanK !== null) {
      computed.tempMeanK = spec.tempMeanK;
      computed.tempMinK = spec.tempMinK;
      computed.tempMaxK = spec.tempMaxK;
    }

    return {
      id: spec.id,
      datasetId: spec.datasetId,
      name: spec.name,
      planet: spec.planet,
      countryOrQuadrangle: spec.countryOrQuadrangle,
      latitude: spec.latitude,
      longitude: spec.longitude,
      spatialExtentKm2: spec.spatialExtentKm2,
      dataOrigin: 'OBSERVATION_REFERENCE',
      elevationDatum: spec.elevationDatum,
      summary: spec.summary,
      features: computed,
    };
  });
}
